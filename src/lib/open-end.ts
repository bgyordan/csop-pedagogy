// Отсъствие без известна крайна дата (напр. болничен, докато колегата е в болница).
// В базата „до“ е условна далечна дата — така всички сметки по дни и месеци работят както досега
// (отсъствието важи за всеки следващ ден), а навсякъде на екрана просто не се показва крайна дата.
// Когато колегата се върне, в „До“ се слага истинската дата.
export const OPEN_END = '2099-12-31'
export const isOpenEnd = (iso?: string | null) => !!iso && iso >= '2099-01-01'
