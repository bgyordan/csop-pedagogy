-- Атестиране 2026 (преди ЕИС): резултатите от заключителния доклад от 13.07.2026 г.
-- Процедура 15.06–15.07.2026 по Заповед № 1015/15.06.2026 на директора; комисия: С. Кьошкерян (председател), Р. Драганчев.
-- Само сигурната информация от доклада: дата и крайна оценка (без точки — в доклада ги няма).
-- Служителите се търсят по име и фамилия. Безопасно за повторно пускане — вече записан ред не се дублира.
-- Ако някой не бъде намерен (или има двама с това име), се показва NOTICE и редът се пропуска.
do $$
declare
  r record;
  sid uuid;
  n int;
begin
  for r in
    select * from (values
      ('Даниела',  'Георгиева', 'Изключително изпълнение'),
      ('Жулиета',  'Стефанова', 'Изключително изпълнение'),
      ('Нина',     'Русева',    'Изключително изпълнение'),
      ('Рая',      'Стефанова', 'Изключително изпълнение'),
      ('Светлана', 'Живкова',   'Изключително изпълнение'),
      ('Диляна',   'Василева',  'Надвишава изискванията'),
      ('Зюхтие',   'Халил',     'Надвишава изискванията'),
      ('Николай',  'Христов',   'Надвишава изискванията')
    ) as t(first_name, last_name, grade)
  loop
    select count(*), min(id::text)::uuid into n, sid
      from public.staff_profiles
      where btrim(first_name) = r.first_name and btrim(last_name) = r.last_name;
    if n <> 1 then
      raise notice 'Пропуснат: % % (намерени: %)', r.first_name, r.last_name, n;
      continue;
    end if;
    if exists (select 1 from public.eval_attest_history where staff_id = sid and attested_on = date '2026-07-13') then
      continue;
    end if;
    insert into public.eval_attest_history (staff_id, attested_on, grade, note)
    values (sid, date '2026-07-13', r.grade,
            'Заповед № 1015/15.06.2026; закл. доклад 13.07.2026; комисия: С. Кьошкерян (пр.), Р. Драганчев');
  end loop;
end $$;
