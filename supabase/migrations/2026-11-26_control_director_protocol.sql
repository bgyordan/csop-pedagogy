-- Самооценката на проверения върви по скалата на протокола
drop function if exists public.control_self_requests();
create or replace function public.control_self_requests()
returns table (check_id uuid, subject text, check_date date, inspector text, criteria jsonb, self_assessment jsonb, self_assessed_at timestamptz, scale int)
language sql stable security definer set search_path = public as $$
  select c.id, c.subject, c.check_date, coalesce(p.first_name || ' ' || p.last_name, ''), c.criteria, s.self_assessment, s.self_assessed_at, c.scale
  from control_check_staff s
  join control_checks c on c.id = s.check_id
  left join staff_profiles p on p.id = c.inspector_id
  where s.staff_id = get_my_staff_id() and s.self_requested_at is not null and c.status = 'draft'
  order by c.check_date
$$;
grant execute on function public.control_self_requests() to authenticated;
